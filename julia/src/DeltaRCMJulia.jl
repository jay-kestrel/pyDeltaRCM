"""
    DeltaRCMJulia

Julia port of the pyDeltaRCM water-routing vertical slice
(`pyDeltaRCM/shared_tools.py` helpers + `pyDeltaRCM/water_tools.py` kernels),
validated bit-exactly against reference dumps generated by
`julia/tools/dump_reference.py` from the unmodified Python/numba sources.

## Index-translation conventions (the port's load-bearing audit)

The Python original is 0-based, C-ordered (row-major), and uses flat index
`0` as the "inactive parcel" sentinel. Julia is 1-based and column-major.
The port fixes ONE convention and applies it everywhere:

1. **Field arrays** (eta, stage, depth, qw, ...): a Python `(L, W)` array
   `A[i0, j0]` (0-based) is stored as the Julia `Matrix{Float32}` of size
   `(W, L)` with `M[j, i] == A[i0, j0]`, `i = i0 + 1`, `j = j0 + 1`.
   Because both layouts put `j0` and columns on the fast axis, the Julia
   matrix has byte-identical memory order to the NumPy array:
   `reshape(bytes, (W, L))` reproduces `A` exactly (see `Npy`).

2. **Parcel index arrays** (current_inds, new_inds, start_indices,
   free_surf_walk_inds) keep the **Python 0-based flat integers verbatim**,
   including the sentinel `0` = inactive parcel. They are converted to
   `(i, j)` field coordinates only at array access:
   `i = f0 ÷ W + 1`, `j = f0 % W + 1`. Keeping the 0-based domain intact
   preserves the Python quirk that an inactive parcel (`f0 == 0`) reads
   cell `(0, 0)` in boundary checks and is pinned to direction `4`.

3. **9-neighbor vectors** (water weights, walk arrays `iwalk_flat` etc.)
   are the C-order flatten of the 3x3 neighborhood: flat position
   `d0 = di*3 + dj` with `di, dj in -1:1`; `d0 == 4` is the center. Julia
   vectors are indexed `d0 + 1`.

4. **RNG**: numpy-legacy MT19937 exactly as numba implements it
   (`MT19937`), passed explicitly; draws are consumed in the Python order.
"""
module DeltaRCMJulia

include("npy.jl")
include("mt19937.jl")
include("shared_tools.jl")
include("water_tools.jl")

end # module
